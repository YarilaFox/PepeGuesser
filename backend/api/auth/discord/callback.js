import { verifyPayload } from "../../../lib/utils.js"
import {
  ADMIN_DISCORD_ID,
  createPlayerSession,
  deniedPath,
  resolveDiscordRedirectUri,
  setSessionCookie
} from "../../../lib/auth.js"
import { upsertPepeGuessrProfileFromDiscord } from "../../../lib/pepeguessr-api.js"

export default async function handler(req, res) {
  const state = typeof req.query.state === "string" ? req.query.state : ""
  const code = typeof req.query.code === "string" ? req.query.code : ""

  if (!code) {
    return res.redirect(deniedPath("missing_code"))
  }

  let codeVerifier = ""
  let nextPath = "/"

  // Preferred flow: signed state + PKCE (generated by /auth/discord/login).
  // Fallback flow: direct Discord authorize URL without state.
  if (state) {
    const payload = verifyPayload(state)
    if (!payload || payload.exp <= Date.now()) {
      return res.redirect(deniedPath("state"))
    }

    codeVerifier = typeof payload.codeVerifier === "string" ? payload.codeVerifier : ""
    nextPath = typeof payload.nextPath === "string" && payload.nextPath ? payload.nextPath : "/"
  }

  try {
    const clientId = process.env.DISCORD_CLIENT_ID || ""
    const clientSecret = process.env.DISCORD_CLIENT_SECRET || ""
    const redirectUri = resolveDiscordRedirectUri(req)

    if (!clientId || !clientSecret || !redirectUri) {
      return res.redirect(deniedPath("config"))
    }

    const tokenParams = new URLSearchParams({
      client_id: clientId,
      client_secret: clientSecret,
      grant_type: "authorization_code",
      code,
      redirect_uri: redirectUri
    })

    if (codeVerifier) {
      tokenParams.set("code_verifier", codeVerifier)
    }

    const tokenResp = await fetch("https://discord.com/api/oauth2/token", {
      method: "POST",
      headers: { "Content-Type": "application/x-www-form-urlencoded" },
      body: tokenParams.toString()
    })

    if (!tokenResp.ok) {
      return res.redirect(deniedPath("token"))
    }

    const tokenData = await tokenResp.json()
    const accessToken = tokenData?.access_token
    if (!accessToken || typeof accessToken !== "string") {
      return res.redirect(deniedPath("token"))
    }

    const userResp = await fetch("https://discord.com/api/users/@me", {
      headers: { Authorization: `Bearer ${accessToken}` }
    })

    if (!userResp.ok) {
      return res.redirect(deniedPath("profile"))
    }

    const user = await userResp.json()
    const isOwner = user?.id === ADMIN_DISCORD_ID

    if (!user?.id) {
      return res.redirect(deniedPath("profile"))
    }

    const profile = await upsertPepeGuessrProfileFromDiscord(user)
    const sessionData = createPlayerSession(profile, isOwner)
    setSessionCookie(res, sessionData)
    return res.redirect(nextPath)
  } catch (error) {
    return res.redirect(deniedPath("callback"))
  }
}
